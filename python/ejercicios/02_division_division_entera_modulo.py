# Ejercicio 02: /, // y %
# Tema trabajado durante las prácticas de Python.

print("14 / 4 =", 14 / 4)
print("14 // 4 =", 14 // 4)
print("14 % 4 =", 14 % 4)

print("23 / 5 =", 23 / 5)
print("23 // 5 =", 23 // 5)
print("23 % 5 =", 23 % 5)

numero = 28
residuo = numero % 2

print("28 % 2 =", residuo)

if residuo == 0:
    print("28 es par")
else:
    print("28 es impar")
